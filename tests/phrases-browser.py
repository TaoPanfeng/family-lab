#!/usr/bin/env python3
"""End-to-end checks for idiom and xiehouyu study pages. Uses actual file:// or HTTP navigation."""
import argparse, functools, json, threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
class Quiet(SimpleHTTPRequestHandler):
 def log_message(self,*args): pass
def main():
 p=argparse.ArgumentParser()
 p.add_argument('--file',action='store_true');p.add_argument('--site',action='store_true')
 p.add_argument('--base');p.add_argument('--browser');p.add_argument('--out',default='.qa/phrases')
 args=p.parse_args()
 out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
 server=None
 if args.base:base=args.base.rstrip('/')
 elif args.file:base=''
 else:
  server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=str(ROOT/'_site' if args.site else ROOT)))
  threading.Thread(target=server.serve_forever,daemon=True).start()
  base='http://127.0.0.1:'+str(server.server_port)
 url=(ROOT/'projects/chinese/phrases.html').as_uri() if args.file else base+'/projects/chinese/phrases.html'
 report={'mode':'file://' if args.file else 'published HTTP' if args.base else 'local HTTP','url':url,'checks':[],'errors':[]}
 def check(name,ok):
  report['checks'].append({'name':name,'passed':bool(ok)})
  if not ok: raise AssertionError(name)
 try:
  with sync_playwright() as p:
   kwargs={'headless':True,'args':['--no-sandbox']}
   if args.browser:kwargs['executable_path']=args.browser
   browser=p.chromium.launch(**kwargs)
   context=browser.new_context(viewport={'width':1440,'height':900},locale='zh-CN',accept_downloads=True)
   page=context.new_page()
   page.on('pageerror',lambda e:report['errors'].append(str(e)))
   page.goto(url,wait_until='load')
   page.wait_for_function('window.PhraseTest')
   check('30 documented idioms and 32 sayings',page.evaluate('PhraseTest.all.length')==62)
   check('default idiom visible',page.locator('#term').inner_text()=='守株待兔')
   check('source work, era and source caveat visible',all(page.locator('#'+x).inner_text() for x in ('source-work','source-era','source-note')))
   check('hidden meaning before guessing',page.locator('#answer').is_hidden())
   page.locator('#my-sentence').fill('还没保存的句子，也不能被看答案和收藏清空。')
   page.locator('#reveal').click()
   check('reveal toggles answer',page.locator('#answer').is_visible())
   check('reveal preserves unsaved sentence',page.locator('#my-sentence').input_value()=='还没保存的句子，也不能被看答案和收藏清空。')
   page.locator('#story-next').click()
   check('story progresses',page.evaluate('PhraseTest.state().stage')==2)
   page.locator('#story-all').click()
   check('three-step story',page.evaluate('PhraseTest.state().stage')==3)
   page.locator('#story-prev').click()
   check('story can step backward',page.evaluate('PhraseTest.state().stage')==2)
   page.locator('#favorite').click()
   check('favorite recorded',page.evaluate("PhraseTest.state().records.favorites.includes('i01')"))
   check('favorite preserves unsaved sentence',page.locator('#my-sentence').input_value()=='还没保存的句子，也不能被看答案和收藏清空。')
   page.locator('#following').click();page.locator('#previous').click()
   check('card navigation preserves draft',page.locator('#my-sentence').input_value()=='还没保存的句子，也不能被看答案和收藏清空。')
   page.locator('#my-sentence').fill('我每天做自己的练习，不守株待兔。')
   page.locator('#save').click()
   page.reload(wait_until='load');page.wait_for_function('window.PhraseTest')
   check('learning record persists across reload',page.evaluate("PhraseTest.state().records.notes['i01']")=='我每天做自己的练习，不守株待兔。')
   page.locator('#search').fill('韩非子')
   check('source full text searchable',page.evaluate("PhraseTest.shown().length>=3"))
   page.locator('#search').fill('不存在的检索词xyz')
   check('empty search disables previous and next',page.locator('#previous').is_disabled() and page.locator('#following').is_disabled())
   page.locator('#clear').click()
   page.locator('#only-faves').check()
   check('favorite filter contains only saved card',page.evaluate('PhraseTest.shown()')==['i01'])
   page.locator('#clear').click()
   page.locator('#tab-saying').click()
   check('sayings are distinct category',page.evaluate('PhraseTest.state().kind')=='saying')
   check('guess stage does not leak second half',page.locator('#term').inner_text().endswith('？') and page.locator('#answer').is_hidden())
   check('example and hint do not leak saying answer',page.evaluate("!document.querySelector('#daily-example').textContent.includes(ChinesePhrases.sayings[0].back)&&!document.querySelector('#pitfall').textContent.includes(ChinesePhrases.sayings[0].back)"))
   page.locator('#reveal').click()
   check('saying answer appears',page.locator('#answer-text').inner_text().count('——')==1)
   page.locator('[data-entry="x23"]').click()
   check('fiction source distinguished from first-use date','年代未详' in page.locator('#source-era').inner_text())
   check('no fake original date for folklore',all(('未详' in e['source']['era'] or '待考' in e['source']['era'] or '不详' in e['source']['era']) for e in page.evaluate('ChinesePhrases.sayings')))
   page.locator('#search').fill('谐音')
   check('search filters by meaning',page.evaluate('PhraseTest.shown().length')>0)
   page.locator('#search').fill('')
   for kind in ('idiom','saying'):
    page.locator('#tab-'+kind).click()
    entries=page.evaluate(f'ChinesePhrases.{"idioms" if kind=="idiom" else "sayings"}')
    for entry in entries:
     id=entry['id'];page.locator('[data-entry="'+id+'"]').click()
     page.locator('#reveal').click()
     check('each source and example render '+id,page.locator('#source-era').inner_text()==entry['source']['era'] and page.locator('#daily-example').inner_text()==entry['example'])
     check('each meaning matches selected entry '+id,page.locator('#meaning').inner_text()==entry['meaning'])
   page.locator('#tab-idiom').click()
   page.locator('.backup summary').click()
   incoming={'app':'family-lab-chinese-phrases','version':1,'favorites':['i02'],'notes':{'i01':'不得覆盖已有句子','i02':'新导入的造句'}}
   page.locator('#import').set_input_files({'name':'merge.json','mimeType':'application/json','buffer':json.dumps(incoming).encode()})
   page.wait_for_function("document.querySelector('#backup-info').textContent.includes('导入成功')")
   check('valid import preserves existing notes and adds new notes',page.evaluate("PhraseTest.state().records.notes.i01==='我每天做自己的练习，不守株待兔。'&&PhraseTest.state().records.notes.i02==='新导入的造句'"))
   page.locator('#only-faves').check()
   check('import refreshes favorite filter',set(page.evaluate('PhraseTest.shown()'))=={'i01','i02'})
   page.locator('#clear').click()
   saved_before=page.evaluate('JSON.stringify(PhraseTest.state().records)')
   page.locator('#import').set_input_files({'name':'invalid.json','mimeType':'application/json','buffer':b'{"notes":{"__proto__":"X"}}'})
   page.wait_for_function("document.querySelector('#backup-info').textContent.includes('未导入')")
   check('invalid import rejected atomically',page.evaluate('JSON.stringify(PhraseTest.state().records)')==saved_before)
   page.locator('#my-sentence').fill('导出时也保留尚未点击保存的草稿。')
   with page.expect_download() as pending:page.locator('#export').click()
   download=pending.value;data=json.loads(Path(download.path()).read_text())
   check('export contains current unsaved draft',data['notes']['i01']=='导出时也保留尚未点击保存的草稿。')
   page.screenshot(path=str(out/'phrases-desktop.png'),full_page=True)
   for width in (320,390,768):
    page.set_viewport_size({'width':width,'height':844})
    check(str(width)+'px has no horizontal page overflow',page.evaluate('document.documentElement.scrollWidth <= innerWidth+2'))
   page.set_viewport_size({'width':390,'height':844})
   page.reload(wait_until='load');page.wait_for_function('window.PhraseTest')
   page.screenshot(path=str(out/'phrases-mobile.png'),full_page=True)
   check('reading remains scrollable',page.evaluate('document.documentElement.scrollHeight>innerHeight+150'))
   # Trusted touchscreen events, not mouse clicks on a narrow viewport.
   mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=2,locale='zh-CN')
   touch=mobile.new_page();touch.on('pageerror',lambda e:report['errors'].append(str(e)))
   touch.goto(url,wait_until='load');touch.wait_for_function('window.PhraseTest')
   touch.locator('#tab-saying').tap();touch.locator('[data-entry="x03"]').tap()
   check('mobile touch selects correct entry',touch.evaluate('PhraseTest.state().selected')=='x03')
   touch.locator('#reveal').tap()
   check('mobile touch reveals answer',touch.locator('#answer').is_visible())
   touch.locator('#my-sentence').fill('我用自己的话说一说。')
   touch.locator('#favorite').tap()
   check('mobile favorite preserves draft',touch.locator('#my-sentence').input_value()=='我用自己的话说一说。')
   touch.locator('#study').scroll_into_view_if_needed()
   touch.evaluate("scrollTo(0,document.querySelector('#study').getBoundingClientRect().top+scrollY)")
   start=touch.evaluate('scrollY')
   cdp=mobile.new_cdp_session(touch)
   cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':360,'y':700}]})
   for y in (650,570,480,390,300):
    cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':360,'y':y}]});touch.wait_for_timeout(30)
   cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
   touch.wait_for_function('(before)=>scrollY>before+20',arg=start)
   check('trusted swipe scrolls reading page',touch.evaluate('scrollY')>start+20)
   touch.screenshot(path=str(out/'phrases-mobile-touch.png'),full_page=True)
   mobile.close()
   denied=browser.new_context()
   denied.add_init_script("const original=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='family-lab.chinese.phrases.v1')throw new DOMException('Blocked','QuotaExceededError');return original.call(this,k,v);};")
   blocked=denied.new_page();blocked.on('pageerror',lambda e:report['errors'].append(str(e)))
   blocked.goto(url,wait_until='load');blocked.wait_for_function('window.PhraseTest')
   blocked.locator('#my-sentence').fill('保存失败时应明确告诉我。');blocked.locator('#save').click()
   check('storage failure never reports a successful save','未能保存' in blocked.locator('#saved-msg').inner_text())
   check('storage failure preserves sentence',blocked.locator('#my-sentence').input_value()=='保存失败时应明确告诉我。')
   denied.close()
   check('no page errors',not report['errors'])
   report['status']='passed'
   browser.close()
 except Exception as exc:
  report['status']='failed';report['fatal']=str(exc);raise
 finally:
  report['passed']=sum(bool(c['passed']) for c in report['checks'])
  report['failed']=sum(not c['passed'] for c in report['checks'])
  (out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
  if server:server.shutdown()
 print('phrases browser checks:',len(report['checks']),'errors:',len(report['errors']))
if __name__=='__main__':main()
